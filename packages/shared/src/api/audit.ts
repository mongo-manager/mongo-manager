/**
 * A live sync's change no person asked for is audited under its new state (`livesync.attention`): only
 * these states (final review: the filter offered states never written).
 */
export const LIVE_SYNC_AUDITED_STATES = [
  'paused',
  'attention',
  'failed',
  'stopped',
  'completed',
] as const satisfies readonly LiveSyncState[]
export type LiveSyncAuditedState = (typeof LIVE_SYNC_AUDITED_STATES)[number]
export type LiveSyncAuditAction = `livesync.${LiveSyncAuditedState}`
export type AuditAction = (typeof AUDIT_ACTIONS)[number] | LiveSyncAuditAction

/** Every action, the live sync states' too, for the log's filter. */
export const ALL_AUDIT_ACTIONS: readonly AuditAction[] = [
  ...AUDIT_ACTIONS,
  ...LIVE_SYNC_AUDITED_STATES.map((s): LiveSyncAuditAction => `livesync.${s}`),
]

