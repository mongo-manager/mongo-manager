/**
 * Plugins wave 3 (spec §3): the words test documents are made of, in English and Turkish. Our own
 * lists (no dependency): common first and last names, places, companies, products and words.
 * Addresses are invented; e-mails and web addresses use reserved example domains only.
 */
export interface Lists {
  firstNames: string[]
  lastNames: string[]
  cities: string[]
  regions: string[]
  countries: Array<[code: string, name: string]>
  streets: string[]
  streetKinds: string[]
  companies: string[]
  companySuffixes: string[]
  departments: string[]
  jobTitles: string[]
  industries: string[]
  products: string[]
  productAdjectives: string[]
  categories: string[]
  colors: string[]
  words: string[]
  weekdays: string[]
  months: string[]
  statuses: string[]
  genders: string[]
  /** A phone number made of digits from the PRNG: `#` is a digit. */
  phoneFormat: string
  postalFormat: string
  /**
   * Languages not written in Latin letters: a Latin spelling for each name and word that goes into an
   * e-mail, a user name, a slug or a domain.
   */
  latin?: Record<string, string>
  /** The family name comes first, with no space (Chinese, Japanese). */
  familyFirst?: boolean
  /** What joins words, a company's name and suffix, a product's adjective and name (default: a space). */
  joiner?: string
  /** What ends a sentence (default: a full stop). */
  sentenceEnd?: string
  /** A product's adjective follows its name (Spanish, Portuguese). */
  adjectiveAfter?: boolean
  /** A product from its adjective and name, where the language joins them its own way (German, Russian). */
  productText?: (adjective: string, product: string) => string
  /** A street from its name and kind, where the language orders them its own way. */
  streetText?: (name: string, kind: string) => string
  /** A street address from its street, kind and number. */
  addressText?: (name: string, kind: string, n: number) => string
}

