// Phase 3a-2 spec §3.1: generate the browser's static shell completion catalogue from the installed
// mongosh (@mongosh/shell-api signatures) and @mongodb-js/mongodb-constants. The browser completes
// from this file alone: no request to the worker for the common cases.
//
//   node scripts/gen-shell-catalogue.mjs          write packages/shared/src/shell/catalogue.generated.ts
//   node scripts/gen-shell-catalogue.mjs --check  exit 1 when the committed file is stale
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const OUT = join(here, '..', '..', 'shared', 'src', 'shell', 'catalogue.generated.ts')

const TYPES = [
  'ShellApi',
  'Database',
  'Collection',
  'Cursor',
  'AggregationCursor',
  'RunCommandCursor',
  'ExplainableCursor',
  'Explainable',
  'ReplicaSet',
  'Shard',
  'Mongo',
  'Session',
  'Bulk',
  'BulkFindOp',
  'ChangeStreamCursor',
  'PlanCache',
  'ShellConfig',
  'Streams',
  'KeyVault',
  'ClientEncryption',
]
const SHELL_COMMANDS = ['it', 'show', 'use']
const SHOW_TARGETS = [
  'automationNotices',
  'collections',
  'databases',
  'dbs',
  'log',
  'logs',
  'nonGenuineMongoDBCheck',
  'profile',
  'roles',
  'startupWarnings',
  'tables',
  'users',
]

/** The generated module's text, deterministic (keys sorted). */
export function buildCatalogue() {
  const fromServer = createRequire(join(here, '..', 'package.json'))
  const fromRuntime = createRequire(fromServer.resolve('@mongosh/browser-runtime-core'))
  const fromAutocomplete = createRequire(fromRuntime.resolve('@mongosh/autocomplete'))
  const { signatures } = fromAutocomplete('@mongosh/shell-api')
  const constants = fromAutocomplete('@mongodb-js/mongodb-constants')

  const types = {}
  for (const type of TYPES) {
    const attributes = signatures[type]?.attributes ?? {}
    const members = {}
    for (const name of Object.keys(attributes).sort()) {
      const attr = attributes[name]
      if (name.startsWith('_')) continue
      const platforms = Array.isArray(attr.platforms) ? attr.platforms : []
      if (!platforms.includes('Browser') && !platforms.includes('CLI')) continue
      members[name] = {
        ...(typeof attr.returnType === 'string' && attr.returnType ? { returnType: attr.returnType } : {}),
        ...(attr.deprecated ? { deprecated: true } : {}),
      }
    }
    types[type] = members
  }
  const names = (list) => [...new Set(list.map((o) => o.name).filter((n) => typeof n === 'string'))].sort()
  const operators = {
    query: names(constants.QUERY_OPERATORS),
    stage: names(constants.STAGE_OPERATORS),
    expression: names(constants.EXPRESSION_OPERATORS),
    conversion: names(constants.CONVERSION_OPERATORS),
    bson: names(constants.BSON_TYPES),
  }
  return `// SPDX-License-Identifier: AGPL-3.0-only
// Copyright (C) 2026 Gokhan OZGEZER
// GENERATED by packages/server/scripts/gen-shell-catalogue.mjs from @mongosh/shell-api and
// @mongodb-js/mongodb-constants. Do not edit: run "pnpm --filter @mongo-manager/server gen:catalogue".
// Phase 3a-2 spec §3.1: the static shell completion catalogue.

export interface ShellMember {
  returnType?: string
  deprecated?: true
}

export const SHELL_TYPES: Record<string, Record<string, ShellMember>> = ${JSON.stringify(types, null, 2)}

export const OPERATORS: {
  query: string[]
  stage: string[]
  expression: string[]
  conversion: string[]
  bson: string[]
} = ${JSON.stringify(operators, null, 2)}

export const SHELL_COMMANDS: string[] = ${JSON.stringify(SHELL_COMMANDS)}

export const SHOW_TARGETS: string[] = ${JSON.stringify(SHOW_TARGETS)}
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = buildCatalogue()
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(OUT, 'utf8')
    } catch {
      // Missing counts as stale.
    }
    if (current.replace(/\r\n/g, '\n') !== text) {
      process.stdout.write(
        'catalogue.generated.ts is stale: run pnpm --filter @mongo-manager/server gen:catalogue\n',
      )
      process.exit(1)
    }
  } else {
    writeFileSync(OUT, text)
    process.stdout.write(`wrote ${OUT}\n`)
  }
}
