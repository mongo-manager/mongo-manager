// Phase 3a-1 spec §3.2: @mongosh/shell-evaluator has one `eval(code)` in the host realm
// (contextless-eval.js). Under --disallow-code-generation-from-strings that eval throws. This
// script compiles the exact code that eval would ever receive — the async-rewriter runtime-support
// code and its `process('1+1')` warm-up — into a real module. Any other string is refused.
//
// The generated module replaces shell-evaluator/lib/contextless-eval.js in the worker bundle. If a
// mongosh upgrade changes either string or the pinned versions, this script fails, so the bundle is
// never built with a stale or mismatched stub.
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pkg = join(here, '..')
const req = createRequire(join(pkg, 'package.json'))
// shell-evaluator is a nested dependency of browser-runtime-core; resolve it from there.
const shellReq = createRequire(req.resolve('@mongosh/browser-runtime-core'))
const resolveShell = (id) => shellReq.resolve(id)

// The versions this generator was written against. mongosh's runtime-support code is internal and
// changes between versions; a mismatch means the two strings below may differ, so we stop.
const PINNED = {
  '@mongosh/async-rewriter2': '2.6.0',
  '@mongosh/shell-evaluator': '5.9.0',
}
for (const [name, want] of Object.entries(PINNED)) {
  const got = (name === '@mongosh/shell-evaluator' ? shellReq : req)(`${name}/package.json`).version
  if (got !== want) {
    console.error(
      `gen-contextless-eval: ${name} is ${got}, expected ${want}. Review mongosh's contextless eval, ` +
        `re-pin the version here, and regenerate.`,
    )
    process.exit(1)
  }
}

// Confirm the file we replace still contains exactly one eval and nothing else of substance.
const original = readFileSync(resolveShell('@mongosh/shell-evaluator/lib/contextless-eval.js'), 'utf8')
const evalCount = (original.match(/\beval\(/g) ?? []).length
if (evalCount !== 1) {
  console.error(`gen-contextless-eval: expected exactly one eval() in contextless-eval.js, found ${evalCount}.`)
  process.exit(1)
}

const AsyncRewriter = req('@mongosh/async-rewriter2').default
const rewriter = new AsyncRewriter()
const support = rewriter.runtimeSupportCode()
const warm = rewriter.process('1+1')

// The two strings are embedded once as data (for the equality guard) and once as a real, compiled
// function body (the code that runs). Compiling here is a bundler step, not runtime code generation.
const out = `/* eslint-disable */
// GENERATED by scripts/gen-contextless-eval.mjs. Do not edit.
// Replaces @mongosh/shell-evaluator's contextless-eval.js so the worker needs no string eval.
// Pinned: @mongosh/async-rewriter2 ${PINNED['@mongosh/async-rewriter2']}, @mongosh/shell-evaluator ${PINNED['@mongosh/shell-evaluator']}.
'use strict'
const SUPPORT = ${JSON.stringify(support)}
const WARM = ${JSON.stringify(warm)}
function runSupport() {
${support}
}
function runWarm() {
${warm}
}
Object.defineProperty(exports, '__esModule', { value: true })
exports.contextlessEval = function contextlessEval(code) {
  if (code === SUPPORT) return runSupport()
  if (code === WARM) return runWarm()
  throw new EvalError('mongo-manager: host eval is disabled in the shell sandbox')
}
`

const target = join(pkg, 'src', 'shell', 'worker', 'contextless-eval.generated.cjs')
writeFileSync(target, out)
console.log(`gen-contextless-eval: wrote ${target} (${out.length} bytes, support ${support.length}, warm ${warm.length})`)
